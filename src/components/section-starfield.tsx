type SectionStarfieldProps = {
  idPrefix: string;
  className?: string;
  density?: "default" | "dense";
};

export function SectionStarfield({
  idPrefix,
  className,
  density = "default",
}: SectionStarfieldProps) {
  const sourceStars =
    density === "dense" ? [...rawStars, ...denseExtraStars] : rawStars;

  const stars = sourceStars.map(([x, y, size, opacity]) => {
    const scaledSize = size * 1.35;
    const scaledOpacity =
      size >= 0.72
        ? Math.min(0.72, opacity * 1.12)
        : size >= 0.48
          ? Math.min(0.62, opacity * 1.08)
          : Math.min(0.85, opacity * 1.1);

    return [x, y, scaledSize, scaledOpacity] as const;
  });

  const softId = `${idPrefix}-star-glow-soft`;
  const brightId = `${idPrefix}-star-glow-bright`;
  const shineId = `${idPrefix}-star-glow-shine`;

  return (
    <svg
      className={className}
      viewBox="0 0 100 100"
      preserveAspectRatio="xMidYMid slice"
      aria-hidden="true"
    >
      <defs>
        <radialGradient id={softId} cx="50%" cy="50%" r="50%">
          <stop offset="0%" stopColor="white" stopOpacity="0.78" />
          <stop offset="55%" stopColor="#eef6ff" stopOpacity="0.28" />
          <stop offset="100%" stopColor="white" stopOpacity="0" />
        </radialGradient>
        <radialGradient id={brightId} cx="50%" cy="50%" r="50%">
          <stop offset="0%" stopColor="white" stopOpacity="0.82" />
          <stop offset="40%" stopColor="#f5fbff" stopOpacity="0.45" />
          <stop offset="100%" stopColor="white" stopOpacity="0" />
        </radialGradient>
        <radialGradient id={shineId} cx="50%" cy="50%" r="50%">
          <stop offset="0%" stopColor="white" stopOpacity="0.88" />
          <stop offset="35%" stopColor="#e8f2ff" stopOpacity="0.42" />
          <stop offset="100%" stopColor="white" stopOpacity="0" />
        </radialGradient>
      </defs>
      {stars.map(([x, y, size, opacity], index) => {
        const fill =
          size >= 1.15
            ? `url(#${shineId})`
            : size >= 0.75
              ? `url(#${brightId})`
              : size >= 0.5
                ? `url(#${softId})`
                : "white";
        const drift = index % 3 === 0;
        const driftVariant = index % 5;

        return (
          <g key={index} transform={`translate(${x} ${y})`}>
            <g
              className={
                drift ? `about-star-drift about-star-drift--${driftVariant}` : undefined
              }
            >
              <circle cx={0} cy={0} r={size} fill={fill} opacity={opacity} />
            </g>
          </g>
        );
      })}
    </svg>
  );
}
